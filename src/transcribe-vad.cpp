struct VoiceActivityDetector::Impl {
    float prev_signal                         = 0.0f;
    alignas(32) float sample_ring_buffer[768] = { 0 };
    alignas(32) float features[40 * 3]        = { 0 };
    alignas(32) float buffer[1026]            = { 0 };
    int16_t rnn_state[128]                    = { 0 };

    void reset() noexcept {
        prev_signal = 0.0f;
        std::memset(sample_ring_buffer, 0, sizeof(sample_ring_buffer));
        std::memset(features, 0, sizeof(features));
        std::memset(buffer, 0, sizeof(buffer));
        std::memset(rnn_state, 0, sizeof(rnn_state));
    }

    float predict_f32(std::span<const float, 256> frame) noexcept {
        constexpr float SCALE              = 32768.0f;
        constexpr float PRE_EMPHASIS_COEFF = 0.97f;
        constexpr float POWER_FAC          = 1.0f / (32768.0f * 32768.0f);

        std::memmove(sample_ring_buffer, sample_ring_buffer + 256, 512 * sizeof(float));
        for (size_t i = 0; i < 256; ++i) {
            float s                     = frame[i] * SCALE;
            sample_ring_buffer[512 + i] = s - PRE_EMPHASIS_COEFF * prev_signal;
            prev_signal                 = s;
        }

        for (size_t i = 0; i < 768; ++i) {
            buffer[i] = sample_ring_buffer[i] * HANN_WINDOW[i];
        }
        std::memset(buffer + 768, 0, (256 + 2) * sizeof(float));

        rfft_1024(buffer);

        auto * comp = reinterpret_cast<Complex32 *>(buffer);
        for (size_t i = 0; i < 513; ++i) {
            buffer[i] = comp[i].norm_sqr() * POWER_FAC;
        }

        std::memmove(features, features + 40, 40 * 2 * sizeof(float));
        float * cur_frame_features = features + 40 * 2;

        for (size_t i = 0; i < 40; ++i) {
            float        per_band_value = 0.0f;
            const auto & mel            = MEL_FILTERS[i];
            for (size_t j = 0; j < mel.count; ++j) {
                per_band_value += buffer[mel.start + j] * mel.coeffs[j];
            }
            cur_frame_features[i] = std::log(per_band_value + 1e-20f);
        }

        float sum_sq = 0.0f;
        for (size_t i = 0; i < 40; ++i) {
            sum_sq += cur_frame_features[i] * cur_frame_features[i];
        }
        float         i_rms  = 1.0f / std::sqrt(sum_sq / 40.0f);
        const float * norm_w = NORM_WEIGHT();
        for (size_t i = 0; i < 40; ++i) {
            cur_frame_features[i] = norm_w[i] * cur_frame_features[i] * i_rms;
        }

        float * buf1 = buffer;
        float * buf2 = buffer + 288;
        input_layer1(features, buf1);
        input_layer2(buf1, buf2);
        int16_t * layer3_out = reinterpret_cast<int16_t *>(buf1);
        input_layer3(buf2, layer3_out);

        int32_t * temp1 = reinterpret_cast<int32_t *>(buffer);
        int32_t * temp2 = temp1 + 288;
        mingru<80>(layer3_out, rnn_state, RNN1_WEIGHT(), temp2);
        mingru<64>(rnn_state, rnn_state + 64, RNN2_WEIGHT(), temp1);

        return output_layer(rnn_state);
    }
};

VoiceActivityDetector::VoiceActivityDetector(float threshold, uint32_t prefill_ms, uint32_t hangover_ms) :
    impl_(new Impl()),
    threshold_(threshold),
    enter_threshold_(threshold),
    exit_threshold_(std::max(0.05f, threshold * 0.70f)),
    hangover_frames_(std::max(1u, hangover_ms / 16u)) {}

VoiceActivityDetector::~VoiceActivityDetector() {
    delete impl_;
}

VoiceActivityDetector::VoiceActivityDetector(VoiceActivityDetector && other) noexcept :
    impl_(other.impl_),
    threshold_(other.threshold_),
    enter_threshold_(other.enter_threshold_),
    exit_threshold_(other.exit_threshold_),
    in_speech_(other.in_speech_),
    accumulated_speech_ms_(other.accumulated_speech_ms_),
    last_score_(other.last_score_),
    last_level_dbfs_(other.last_level_dbfs_),
    hangover_frames_(other.hangover_frames_),
    hangover_rem_(other.hangover_rem_) {
    other.impl_ = nullptr;
}

VoiceActivityDetector & VoiceActivityDetector::operator=(VoiceActivityDetector && other) noexcept {
    if (this != &other) {
        delete impl_;
        impl_                  = other.impl_;
        threshold_             = other.threshold_;
        enter_threshold_       = other.enter_threshold_;
        exit_threshold_        = other.exit_threshold_;
        in_speech_             = other.in_speech_;
        accumulated_speech_ms_ = other.accumulated_speech_ms_;
        last_score_            = other.last_score_;
        last_level_dbfs_       = other.last_level_dbfs_;
        hangover_frames_       = other.hangover_frames_;
        hangover_rem_          = other.hangover_rem_;
        other.impl_            = nullptr;
    }
    return *this;
}

float VoiceActivityDetector::predict_f32(FrameSpan frame) noexcept {
    if (!impl_) {
        return 0.0f;
    }
    // Branchless clamp [-1.0, 1.0]
    alignas(32) float clamped[FRAME_SAMPLES];
    for (size_t i = 0; i < FRAME_SAMPLES; ++i) {
        clamped[i] = std::clamp(frame[i], -1.0f, 1.0f);
    }
    return impl_->predict_f32(std::span<const float, 256>(clamped));
}

std::expected<bool, VadError> VoiceActivityDetector::process_frame(FrameSpan frame, float * out_score) noexcept {
    if (!impl_) {
        return std::unexpected(VadError::Uninitialized);
    }
    for (size_t i = 0; i < FRAME_SAMPLES; ++i) {
        if (!std::isfinite(frame[i])) {
            return std::unexpected(VadError::InvalidInput);
        }
    }

    // Compute RMS dBFS
    double sum_sq = 0.0;
    for (size_t i = 0; i < FRAME_SAMPLES; ++i) {
        sum_sq += static_cast<double>(frame[i]) * static_cast<double>(frame[i]);
    }
    double mean_sq   = sum_sq / 256.0;
    last_level_dbfs_ = (mean_sq > 1e-12) ? static_cast<float>(10.0 * std::log10(mean_sq)) : -120.0f;

    float score = 0.0f;
    // Sub-microsecond energy pre-gate: skip neural net if silence (< -45 dBFS) and not in speech
    if (!in_speech_ && last_level_dbfs_ < -45.0f) {
        score = 0.0f;
    } else {
        score = predict_f32(frame);
    }
    last_score_ = score;
    if (out_score) {
        *out_score = score;
    }

    // Dual-threshold hysteresis gate
    if (!in_speech_) {
        if (score >= enter_threshold_) {
            in_speech_    = true;
            hangover_rem_ = hangover_frames_;
            accumulated_speech_ms_ += 16;
        }
    } else {
        if (score >= exit_threshold_) {
            hangover_rem_ = hangover_frames_;
            accumulated_speech_ms_ += 16;
        } else if (hangover_rem_ > 0) {
            --hangover_rem_;
            accumulated_speech_ms_ += 16;
        } else {
            in_speech_ = false;
        }
    }
    return in_speech_;
}

void VoiceActivityDetector::reset() noexcept {
    if (impl_) {
        impl_->reset();
    }
    in_speech_             = false;
    accumulated_speech_ms_ = 0;
    last_score_            = 0.0f;
    last_level_dbfs_       = -100.0f;
    hangover_rem_          = 0;
}

void VoiceActivityDetector::set_threshold(float threshold) noexcept {
    threshold_       = std::clamp(threshold, 0.05f, 0.95f);
    enter_threshold_ = threshold_;
    exit_threshold_  = std::max(0.05f, threshold_ * 0.70f);
}

