void input_layer1(const float * features, float * output) noexcept {
    constexpr size_t NUM_FRAMES             = 3;
    constexpr size_t NUM_FEATURES           = 40;
    constexpr size_t KERNEL_SIZE            = 3;
    constexpr size_t DEPTHWISE_NUM_FEATURES = (NUM_FEATURES - KERNEL_SIZE) + 1;  // 38
    constexpr size_t OUT_CHANNELS           = 16;
    constexpr size_t POOL_KERNEL_SIZE       = 3;
    constexpr size_t POOL_STRIDE            = 2;
    constexpr size_t POOLED_COLS            = (DEPTHWISE_NUM_FEATURES - POOL_KERNEL_SIZE) / POOL_STRIDE + 1;  // 18

    std::memset(output, 0, OUT_CHANNELS * POOLED_COLS * sizeof(float));
    float         row[DEPTHWISE_NUM_FEATURES] = { 0 };
    const float * l1_kernel                   = LAYER1_KERNEL();
    const float * l1_weight                   = LAYER1_WEIGHT();
    const float * l1_bias                     = LAYER1_BIAS();

    for (size_t ox = 0; ox < DEPTHWISE_NUM_FEATURES; ++ox) {
        float sum = 0.0f;
        for (size_t kh = 0; kh < KERNEL_SIZE; ++kh) {
            for (size_t kw = 0; kw < KERNEL_SIZE; ++kw) {
                size_t input_idx = kh * NUM_FEATURES + (ox + kw);
                sum += features[input_idx] * l1_kernel[kh * KERNEL_SIZE + kw];
            }
        }
        row[ox] = sum;
    }

    for (size_t c = 0; c < OUT_CHANNELS; ++c) {
        float new_row[DEPTHWISE_NUM_FEATURES];
        float wc = l1_weight[c];
        float bc = l1_bias[c];
        for (size_t ox = 0; ox < DEPTHWISE_NUM_FEATURES; ++ox) {
            new_row[ox] = row[ox] * wc + bc;
        }

        size_t out_row_offs = POOLED_COLS * c;
        for (size_t q = 0; q < POOLED_COLS; ++q) {
            float max_val = output[out_row_offs + q];  // acts as ReLU since initialized to 0
            for (size_t x = 0; x < POOL_KERNEL_SIZE; ++x) {
                max_val = std::max(max_val, new_row[q * POOL_STRIDE + x]);
            }
            output[out_row_offs + q] = max_val;
        }
    }
}

void input_layer2(const float * features, float * output) noexcept {
    constexpr size_t IN_FEATURES            = 18;
    constexpr size_t OUT_FEATURES           = 9;
    constexpr size_t HORIZONTAL_KERNEL_SIZE = 3;
    constexpr size_t STRIDE                 = 2;
    constexpr size_t CHANNELS               = 16;
    const float *    l2_kernel              = LAYER2_KERNEL();
    const float *    l2_weight              = LAYER2_WEIGHT();
    const float *    l2_bias                = LAYER2_BIAS();

    for (size_t ox = 0; ox < OUT_FEATURES; ++ox) {
        float dw[CHANNELS] = { 0 };
        for (size_t c = 0; c < CHANNELS; ++c) {
            float sum = 0.0f;
            for (size_t kw = 0; kw < HORIZONTAL_KERNEL_SIZE; ++kw) {
                intptr_t ix = static_cast<intptr_t>(ox * STRIDE + kw) - 1;
                if (ix >= 0 && ix < static_cast<intptr_t>(IN_FEATURES)) {
                    sum += features[c * IN_FEATURES + static_cast<size_t>(ix)] *
                           l2_kernel[c * HORIZONTAL_KERNEL_SIZE + kw];
                }
            }
            dw[c] = sum;
        }
        for (size_t oc = 0; oc < CHANNELS; ++oc) {
            float ic = 0.0f;
            for (size_t c = 0; c < CHANNELS; ++c) {
                ic += dw[c] * l2_weight[oc * CHANNELS + c];
            }
            output[oc * OUT_FEATURES + ox] = std::max(0.0f, ic + l2_bias[oc]);
        }
    }
}

void input_layer3(const float * features, int16_t * output) noexcept {
    constexpr size_t IN_FEATURES            = 9;
    constexpr size_t OUT_FEATURES           = 5;
    constexpr size_t HORIZONTAL_KERNEL_SIZE = 3;
    constexpr size_t STRIDE                 = 2;
    constexpr size_t CHANNELS               = 16;
    const float *    l3_kernel              = LAYER3_KERNEL();
    const float *    l3_weight              = LAYER3_WEIGHT();

    for (size_t ox = 0; ox < OUT_FEATURES; ++ox) {
        float dw[CHANNELS] = { 0 };
        for (size_t c = 0; c < CHANNELS; ++c) {
            float sum = 0.0f;
            for (size_t kw = 0; kw < HORIZONTAL_KERNEL_SIZE; ++kw) {
                intptr_t ix = static_cast<intptr_t>(ox * STRIDE + kw) - 1;
                if (ix >= 0 && ix < static_cast<intptr_t>(IN_FEATURES)) {
                    sum += features[c * IN_FEATURES + static_cast<size_t>(ix)] *
                           l3_kernel[c * HORIZONTAL_KERNEL_SIZE + kw];
                }
            }
            dw[c] = sum;
        }
        for (size_t oc = 0; oc < CHANNELS; ++oc) {
            float ic = 0.0f;
            for (size_t c = 0; c < CHANNELS; ++c) {
                ic += dw[c] * l3_weight[oc * CHANNELS + c];
            }
            float scaled               = std::round(ic * 32768.0f);
            scaled                     = std::clamp(scaled, -32768.0f, 32767.0f);
            output[ox * CHANNELS + oc] = static_cast<int16_t>(scaled);
        }
    }
}

template <size_t IN_DIM>
void mingru(const int16_t * features, int16_t * h, const int16_t * weight, int32_t * temp) noexcept {
    for (size_t d = 0; d < 128; ++d) {
        int32_t o  = 0;
        size_t  ri = d * IN_DIM;
        for (size_t f = 0; f < IN_DIM; ++f) {
            o += static_cast<int32_t>(features[f]) * static_cast<int32_t>(weight[ri + f]);
        }
        temp[d] = o;
    }

    for (size_t i = 0; i < 64; ++i) {
        int64_t g = std::clamp<int64_t>(static_cast<int64_t>(temp[64 + i]) << 2, 0, 16777215);
        int64_t y = (16777215 - g) * (static_cast<int64_t>(h[i]) << 9) + g * static_cast<int64_t>(temp[i]);
        h[i]      = static_cast<int16_t>(std::clamp<int64_t>(y >> 33, -32768, 32767));
    }
}

inline float sigmoid(float x) noexcept {
    return 1.0f / (1.0f + std::exp(-x));
}

float output_layer(const int16_t * state) noexcept {
    int32_t         out           = 0;
    const int16_t * output_weight = OUTPUT_WEIGHT();
    for (size_t f = 0; f < 128; ++f) {
        out += static_cast<int32_t>(state[f]) * static_cast<int32_t>(output_weight[f]);
    }
    return sigmoid(static_cast<float>(out) / 16777216.0f);
}

