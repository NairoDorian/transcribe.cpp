struct Complex32 {
    float re = 0.0f;
    float im = 0.0f;

    constexpr Complex32() = default;

    constexpr Complex32(float r, float i) : re(r), im(i) {}

    [[nodiscard]] constexpr float norm_sqr() const noexcept { return re * re + im * im; }

    constexpr Complex32 operator+(const Complex32 & rhs) const noexcept { return { re + rhs.re, im + rhs.im }; }

    constexpr Complex32 operator-(const Complex32 & rhs) const noexcept { return { re - rhs.re, im - rhs.im }; }

    constexpr Complex32 operator*(const Complex32 & rhs) const noexcept {
        return { re * rhs.re - im * rhs.im, re * rhs.im + im * rhs.re };
    }

    constexpr Complex32 operator*(float rhs) const noexcept { return { re * rhs, im * rhs }; }
};

template <size_t N> struct CFft {
    static void compute_butterflies(Complex32 * x) noexcept {
        constexpr size_t m            = N / 2;
        constexpr size_t u            = m / 2;
        constexpr size_t table_len    = 255;
        constexpr size_t table_stride = (table_len + 1) * 4 / N;

        CFft<m>::compute_butterflies(x);
        CFft<m>::compute_butterflies(x + m);

        // k = 0
        Complex32 x_0 = x[0];
        Complex32 x_m = x[m];
        x[0]          = x_0 + x_m;
        x[m]          = x_0 - x_m;

        for (size_t k = 1; k < u; ++k) {
            size_t    s  = k * table_stride;
            float     re = SINE_TABLE[table_len - s] * -1.0f;
            float     im = SINE_TABLE[s - 1];
            Complex32 twiddle{ re, im };
            Complex32 x_k  = x[k];
            Complex32 x_km = x[k + m];
            Complex32 y    = twiddle * x_km;
            x[k]           = x_k + y;
            x[k + m]       = x_k - y;
        }

        Complex32 x_u  = x[u];
        Complex32 x_um = x[u + m];
        Complex32 y    = x_um * Complex32{ 0.0f, -1.0f };
        x[u]           = x_u + y;
        x[u + m]       = x_u - y;

        for (size_t k = u + 1; k < m; ++k) {
            size_t    s  = (k - u) * table_stride;
            float     re = SINE_TABLE[s - 1];
            float     im = SINE_TABLE[table_len - s];
            Complex32 twiddle{ re, im };
            Complex32 x_k  = x[k];
            Complex32 x_km = x[k + m];
            Complex32 y    = twiddle * x_km;
            x[k]           = x_k + y;
            x[k + m]       = x_k - y;
        }
    }
};

template <> struct CFft<1> {
    static void compute_butterflies(Complex32 *) noexcept {}
};

template <> struct CFft<2> {
    static void compute_butterflies(Complex32 * x) noexcept {
        Complex32 x_0 = x[0];
        Complex32 x_1 = x[1];
        x[0]          = x_0 + x_1;
        x[1]          = x_0 - x_1;
    }
};

void rfft_1024(float * buffer_1026) noexcept {
    auto * comp = reinterpret_cast<Complex32 *>(buffer_1026);
    for (size_t i = 0; i < 512; ++i) {
        size_t j = BITREV_512[i];
        if (i < j) {
            std::swap(comp[i], comp[j]);
        }
    }
    CFft<512>::compute_butterflies(comp);

    constexpr size_t m            = 512;
    constexpr size_t table_len    = 255;
    constexpr size_t table_stride = 1;

    Complex32 x0 = comp[0];
    comp[0]      = Complex32{ x0.re + x0.im, x0.re - x0.im };

    constexpr size_t u = 256;
    for (size_t k = 1; k < u; ++k) {
        size_t s          = k * table_stride;
        float  twiddle_re = SINE_TABLE[table_len - s] * -1.0f;
        float  twiddle_im = SINE_TABLE[s - 1];

        Complex32 x_k  = comp[k];
        Complex32 x_nk = comp[m - k];
        Complex32 sum{ (x_k.re + x_nk.re) * 0.5f, (x_k.im + x_nk.im) * 0.5f };
        Complex32 diff{ (x_k.re - x_nk.re) * 0.5f, (x_k.im - x_nk.im) * 0.5f };

        comp[k]     = Complex32{ sum.re + twiddle_re * sum.im + twiddle_im * diff.re,
                                 diff.im + twiddle_im * sum.im - twiddle_re * diff.re };
        comp[m - k] = Complex32{ sum.re - twiddle_re * sum.im - twiddle_im * diff.re,
                                 -diff.im + twiddle_im * sum.im - twiddle_re * diff.re };
    }

    Complex32 xu = comp[u];
    comp[u]      = Complex32{ xu.re, -xu.im };

    comp[512].re = comp[0].im;
    comp[512].im = 0.0f;
    comp[0].im   = 0.0f;
}

